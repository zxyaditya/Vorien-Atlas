"""Atlas Validation Framework — Profile dataclasses.

A ValidationProfile is FIRST-CLASS METADATA attached to every feature,
analogous to `formula`, `params`, `perspective`. It answers: what has
been mathematically proven about this feature, and where are its gaps?

Generated by the ValidationRunner (see runner.py). Not a test-run
artefact — a permanent characteristic of the feature.
"""
from __future__ import annotations
from dataclasses import dataclass, field, asdict
from typing import Any, Dict, List, Optional

from .declaration import FeatureValidation, Identity


@dataclass
class GateResult:
    gate: str
    status: str          # "pass" | "fail" | "n/a" | "exempt" | "not_declared" | "error"
    evidence: Dict[str, Any] = field(default_factory=dict)
    duration_ms: float = 0.0

    def to_dict(self) -> Dict[str, Any]:
        return {"gate": self.gate, "status": self.status,
                "evidence": self.evidence, "duration_ms": self.duration_ms}


@dataclass
class IdentityResult:
    name: str
    condition: str
    expected: str
    status: str                                # "pass" | "fail" | "skipped" | "error"
    max_deviation: Optional[float] = None
    tolerance: float = 1e-9
    duration_ms: float = 0.0
    golden: bool = False
    error: Optional[str] = None

    def to_dict(self) -> Dict[str, Any]:
        return {k: v for k, v in asdict(self).items() if v is not None or k in
                ("max_deviation", "error")}


@dataclass
class ValidationProfile:
    """Metadata block attached (in-memory) to every feature after a run.

    Design intent: this is the permanent characteristic of the feature
    — 'what has been mathematically proven about it'. Any future
    persistence layer (Postgres migration, KNOWN_LIMITATIONS §6) can
    serialise/deserialise this dataclass directly.
    """
    feature_id: str
    declaration: FeatureValidation

    # Certified truth:
    gate_results: List[GateResult] = field(default_factory=list)
    identity_results: List[IdentityResult] = field(default_factory=list)

    # Book 1 commitment tracking:
    invariants_committed: List[str] = field(default_factory=list)
    invariants_verified: List[str] = field(default_factory=list)

    # Rollup:
    coverage_score: float = 0.0
    last_run: str = ""

    # Runtime characterisation:
    complexity_declared: str = "O(n)"
    complexity_measured_ms_per_1000_rows: Optional[float] = None

    # Soft-fail signals:
    warnings: List[str] = field(default_factory=list)

    def to_dict(self) -> Dict[str, Any]:
        d = {
            "feature_id": self.feature_id,
            "declaration": {
                "gates": self.declaration.gates,
                "nan_behavior": self.declaration.nan_behavior,
                "degenerate_value": self.declaration.degenerate_value,
                "exemptions": self.declaration.exemptions,
                "properties": self.declaration.properties,
                "invariants": self.declaration.invariants,
                "assumptions": self.declaration.assumptions,
                "complexity": self.declaration.complexity,
                "stability": self.declaration.stability,
                "requires_context": self.declaration.requires_context,
                "bridge": self.declaration.bridge,
                "identities": [
                    {"name": i.name, "condition": i.condition,
                     "expected": i.expected, "golden": i.golden,
                     "tolerance": i.tolerance}
                    for i in self.declaration.identities
                ],
            },
            "gate_results": [g.to_dict() for g in self.gate_results],
            "identity_results": [ir.to_dict() for ir in self.identity_results],
            "invariants_committed": self.invariants_committed,
            "invariants_verified": self.invariants_verified,
            "coverage_score": round(self.coverage_score, 4),
            "last_run": self.last_run,
            "complexity_declared": self.complexity_declared,
            "complexity_measured_ms_per_1000_rows": self.complexity_measured_ms_per_1000_rows,
            "warnings": self.warnings,
        }
        return d

    def summary(self) -> Dict[str, Any]:
        """Compact summary suitable for report rollups."""
        counts = {"pass": 0, "fail": 0, "n/a": 0, "exempt": 0,
                  "not_declared": 0, "error": 0}
        for g in self.gate_results:
            counts[g.status] = counts.get(g.status, 0) + 1
        id_counts = {"pass": 0, "fail": 0, "skipped": 0, "error": 0}
        for ir in self.identity_results:
            id_counts[ir.status] = id_counts.get(ir.status, 0) + 1
        return {
            "feature_id": self.feature_id,
            "coverage_score": round(self.coverage_score, 4),
            "gates": counts,
            "identities": id_counts,
            "warnings": len(self.warnings),
        }
